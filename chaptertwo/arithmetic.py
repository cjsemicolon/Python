'''For each of the arithmetic operators +, -, *, /, // and **, display the
value of an expression with 27.5 as the left operand and 2 as the right operand.'''


sum = 27.5 + 2
print(sum)
substraction = 27.5 - 2
print(substraction)
multiplication = 27.5 * 2
print(multiplication)
true_division = 27.5/2
print(true_division)
floor_division = 27.5//2
print(floor_division )
raise_to_power = 27.5 ** 2
print(raise_to_power)
